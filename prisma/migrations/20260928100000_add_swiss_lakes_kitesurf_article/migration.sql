> **Réponse courte :** depuis 2016, le kitesurf est autorisé par principe sur les eaux suisses. Les cantons et les communes peuvent toutefois l’interdire ou le limiter sur un lac, une rive, une baie, une réserve naturelle ou une zone de départ. Sur un lac intercantonal, la réponse peut donc changer au milieu du plan d’eau.

**Dernière vérification des sources officielles : 28 septembre 2026.** Ce guide couvre les principaux lacs documentés par les autorités. Il ne remplace ni les panneaux sur place, ni les avis temporaires, ni une confirmation auprès du service cantonal de la navigation.

## Lire les statuts

- **🟢 Autorisé** : aucune restriction particulière identifiée au-delà des règles générales de navigation.
- **🟠 Autorisé avec restrictions** : seule une partie du lac est ouverte, ou des zones, horaires et accès doivent être respectés.
- **🔴 Interdit** : la pratique est interdite sur le territoire cantonal ou le plan d’eau indiqué.
- **⚪ À vérifier** : aucune source officielle assez précise n’a été intégrée à cette édition.

Dans la pratique, la majorité des grands lacs suisses se trouvent dans la catégorie **orange**.

## Suisse romande

### Lac Léman — 🟠 autorisé avec restrictions

Sur les eaux vaudoises, le kitesurf reste autorisé sous réserve des zones protégées, des ports, des débarcadères et des règles locales de départ et d’arrivée. À Genève, il est interdit en aval de la ligne **Vengeron–Tour-Carrée** ainsi qu’aux abords des débarcadères.

Le Léman est international : ce statut ne décrit pas les eaux françaises. Il faut vérifier la rive depuis laquelle on part et le secteur dans lequel on navigue.

### Lac de Neuchâtel — 🟠 autorisé avec restrictions

La partie neuchâteloise est expressément ouverte au kitesurf. Le canton impose notamment une distance minimale de 200 mètres avec les bateaux concessionnaires et les débarcadères. Les cantons de Vaud et de Fribourg autorisent également la pratique sur leurs secteurs, avec des réserves naturelles, des zones interdites et des règles d’accès locales.

Les baies protégées, la Grande Cariçaie et la signalisation lacustre demandent une attention particulière. « Autorisé sur le lac » ne signifie pas « départ possible depuis n’importe quelle plage ».

### Lac de Joux — 🟠 autorisé avec restrictions

Le canton de Vaud maintient l’autorisation sur le lac de Joux. Les zones protégées, les ports, les débarcadères et les restrictions communales restent prioritaires. Les autres petits plans d’eau de la vallée ne doivent pas être assimilés automatiquement au lac de Joux.

### Lac de la Gruyère — 🟠 autorisé avec restrictions

Le canton de Fribourg autorise le kitesurf sur de larges parties du lac. Certaines surfaces restent exclues pour protéger l’avifaune, notamment vers les réserves naturelles. Les communes peuvent aussi encadrer les zones de mise à l’eau et d’atterrissage.

[Voir le guide local du lac de la Gruyère](https://www.openwind.ch/fr/vent-en-direct/lac-de-la-gruyere)

### Lac de Morat — 🟠 autorisé avec restrictions

De larges parties des eaux fribourgeoises sont ouvertes, mais les réserves ornithologiques et les zones interdites doivent être contournées. Le lac étant partagé entre Fribourg et Vaud, il faut contrôler la réglementation correspondant à la rive utilisée.

### Lac de Schiffenen — 🟠 autorisé sur une partie seulement

Le canton de Fribourg n’ouvre qu’une portion du lac au kitesurf. Il faut consulter la carte annexée à la réglementation cantonale avant toute mise à l’eau. Les autres plans d’eau fribourgeois qui ne figurent pas parmi les quatre lacs ouverts sont considérés comme zones d’exclusion.

### Lacs de Bienne, de Thoune et de Brienz — 🟠 autorisés avec zones interdites

Dans le canton de Berne, le kitesurf est autorisé par principe. La police des eaux publie une carte détaillée pour chacun de ces trois lacs.

- **Bienne** : la baie de Bienne à l’est de la ligne officielle, les réserves autour de l’île Saint-Pierre et le delta de Hagneck sont notamment interdits.
- **Thoune** : les bassins supérieur et inférieur comprennent des secteurs fermés à la pratique.
- **Brienz** : les zones ouvertes et interdites sont indiquées sur le mémento officiel de la police des eaux.

Pour ces lacs, la carte officielle fait foi : un résumé textuel ne permet pas de suivre précisément les limites sur l’eau.

## Suisse alémanique

### Lac de Zurich — 🟠 statut différent selon le canton

Dans la partie zurichoise, le kitesurf est autorisé avec plusieurs exclusions : bassin inférieur de la ville de Zurich, proximité des débarcadères, bains publics et entrées de ports, ainsi qu’un périmètre autour des îles Ufenau et Lützelau.

Dans la partie saint-galloise du lac de Zurich et du Zürich-Obersee, le kitesurf est interdit. Avant de traverser le lac, il faut donc identifier précisément la frontière cantonale et vérifier également les règles du canton de Schwytz.

### Walensee — 🟠 autorisé avec restrictions

Le kitesurf est autorisé, sauf sur les surfaces fermées publiées par le canton de Saint-Gall. Sont notamment concernés la baie de Weesen, les abords des débarcadères, des bains et des ports, la zone de Gosten Ost et une partie de la baie de Walenstadt. Un corridor spécifique est prévu pour certains départs et arrivées.

### Lac de Sempach — 🟠 secteur sud autorisé

Le canton de Lucerne ouvre le secteur sud du lac, entre la ligne Nottwil–Eich et Sempach, avec des limites liées aux zones riveraines et protégées. Le passage de la zone riveraine doit se faire par le chemin le plus court pour partir ou revenir à un endroit adapté.

### Lac des Quatre-Cantons — 🟠 autorisation partielle documentée

Dans la partie lucernoise, le kitesurf est autorisé en dehors des baies de Lucerne et de Horw délimitées par le canton. Le lac touche plusieurs cantons : cette indication ne vaut pas automatiquement pour Uri, Schwytz, Obwald et Nidwald.

### Lac de Zoug — 🟠 autorisation partielle documentée

La partie lucernoise est ouverte à l’exception de la zone riveraine intérieure. Pour les autres rives, il faut consulter le canton compétent avant de naviguer.

### Greifensee, Pfäffikersee et Türlersee — 🔴 interdits

Le canton de Zurich interdit le kitesurf sur ces lacs, notamment pour des motifs de protection des oiseaux d’eau et de la nature. Les petits lacs zurichois ne doivent pas être considérés comme ouverts par défaut.

### Lac de Constance, rive saint-galloise — 🔴 interdit

Le kitesurf est interdit sur la partie saint-galloise du lac de Constance en raison de la réserve d’oiseaux d’eau et migrateurs qui longe cette rive. Les règles peuvent différer sur les autres rives suisses, allemandes et autrichiennes.

## Lacs non classés dans cette édition — ⚪ à vérifier

Le lac Majeur, le lac de Lugano, le lac de Constance hors Saint-Gall, le lac de Zoug hors Lucerne et de nombreux lacs alpins ne sont pas classés ici. Cela ne signifie ni « autorisé » ni « interdit » : leur cadre officiel n’a pas encore été vérifié et synthétisé pour cette page.

Cette liste sera enrichie au fur et à mesure que des sources cantonales précises et actuelles seront intégrées.

## Les règles fédérales qui s’appliquent partout

Même sur un secteur ouvert, les règles générales restent obligatoires :

1. naviguer uniquement **de jour, par temps clair, entre 8 h et 21 h** ;
2. emporter au minimum une **aide à la flottaison conforme** ;
3. disposer d’une **assurance responsabilité civile** adaptée au kitesurf ;
4. céder la priorité aux autres bateaux conformément aux règles de navigation ;
5. respecter les roseaux, les plantes aquatiques, les réserves naturelles, les bouées jaunes et la signalisation locale ;
6. utiliser uniquement un accès où le départ et l’atterrissage sont autorisés et suffisamment sûrs.

Des distances supplémentaires peuvent être imposées par le droit cantonal, notamment autour des bateaux de ligne, des débarcadères, des ports et des plages publiques.

## La vérification à faire avant chaque session

Une règle peut évoluer et une interdiction temporaire peut être décidée pour une manifestation, une crue, des travaux, la nidification ou un autre enjeu de sécurité.

Avant de gonfler l’aile :

- ouvre la page officielle du canton concerné ;
- consulte la carte des zones lorsqu’elle existe ;
- vérifie les panneaux et les bouées sur place ;
- confirme que la plage autorise réellement le départ et l’atterrissage ;
- en cas de doute, contacte la police du lac ou le service cantonal de la navigation.

